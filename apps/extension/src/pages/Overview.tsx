import { useState } from 'react';
import { useStore } from '../store';
import { api } from '../lib/api';
import { useAsync } from '../lib/hooks';
import { Header } from '../components/layout';
import { Card, SectionHeader, Stat, Skeleton, ErrorState, Badge, Select, SourceNote, Button, EmptyState } from '../components/ui';
import { ViewsLineChart } from '../components/charts';
import { formatCompact, formatNumber, formatRelative } from '../lib/format';
import type { DashboardResponse } from '@shared';

const RANGE_OPTIONS = [
  { value: '7', label: 'Last 7 days' },
  { value: '28', label: 'Last 28 days' },
  { value: '90', label: 'Last 90 days' },
  { value: '365', label: 'Last 365 days' },
];

export function OverviewPage(): React.JSX.Element {
  const { activeChannel } = useStore();
  const [range, setRange] = useState('28');
  const [syncing, setSyncing] = useState(false);

  const dashboard = useAsync<DashboardResponse | null>(
    async () => (activeChannel ? api.dashboard(activeChannel.id, Number(range)) : null),
    [activeChannel?.id, range],
  );
  const data = dashboard.data;

  async function runSync(): Promise<void> {
    if (!activeChannel) return;
    setSyncing(true);
    try {
      await api.syncChannel(activeChannel.id);
      dashboard.refetch();
    } finally {
      setSyncing(false);
    }
  }

  return (
    <div className="pb-10">
      <Header title="Overview" subtitle={activeChannel ? `${activeChannel.channelTitle}` : undefined}>
        <Select value={range} onChange={setRange} options={RANGE_OPTIONS} />
        <Button variant="ghost" className="!text-xs" loading={syncing} onClick={() => void runSync()}>
          Sync
        </Button>
      </Header>

      <div className="space-y-4 px-5 py-4">
        {dashboard.loading && <Skeleton rows={6} height="h-20" />}
        {dashboard.error && <ErrorState message={dashboard.error} retry={dashboard.refetch} />}

        {data && (
          <>
            <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
              <Stat
                label="Subscribers"
                value={formatCompact(data.totals.subscribers)}
                hint={
                  data.deltas.subscribersChange != null
                    ? `${data.deltas.subscribersChange >= 0 ? '+' : ''}${formatNumber(data.deltas.subscribersChange)} since first snapshot`
                    : undefined
                }
              />
              <Stat label="Channel views" value={formatCompact(data.totals.totalViews)} hint="lifetime, channel snapshot" />
              <Stat label={`Views (${range}d)`} value={formatCompact(data.totals.periodViews)} delta={data.deltas.viewsChangePct} hint="vs previous period" />
              <Stat
                label="Watch time"
                value={data.totals.periodWatchMinutes != null ? `${formatCompact(data.totals.periodWatchMinutes)} min` : '-'}
                hint={data.totals.averageViewDurationSeconds != null ? `avg view duration ${Math.round(data.totals.averageViewDurationSeconds)}s` : 'private analytics'}
              />
            </div>

            <Card>
              <SectionHeader title="Daily views" subtitle="Private daily metrics via YouTube Analytics API (authorized scopes only)." />
              {data.timeseries.length > 0 ? (
                <ViewsLineChart data={data.timeseries as unknown as Record<string, unknown>[]} />
              ) : (
                <EmptyState
                  title="No analytics rows yet"
                  body="Click Sync to pull daily metrics. If this persists, the Google connection may lack the yt-analytics.readonly scope - reconnect in Settings."
                />
              )}
            </Card>

            <Card>
              <SectionHeader
                title="AI summary"
                subtitle={
                  data.insights.source === 'ai'
                    ? `Generated by ${data.insights.model ?? 'AI'} from your channel data - interpretation grounded in the numbers above, not guarantees.`
                    : 'Rule-based summary (no AI provider configured). Add an AI key in Settings for richer analysis.'
                }
              />
              <InsightGrid insights={data.insights} />
            </Card>

            <div className="grid grid-cols-1 gap-4 xl:grid-cols-2">
              <Card>
                <SectionHeader title="Top performers" subtitle="Ranked by views/day since publish." />
                <VideoList videos={data.topVideos} />
              </Card>
              <Card>
                <SectionHeader title="Needs attention" subtitle="Lowest views/day in the period." />
                <VideoList videos={data.underperformingVideos} />
              </Card>
            </div>

            <Card>
              <SectionHeader title="Recent uploads" />
              <div className="space-y-1.5">
                {data.recentUploads.length === 0 && <p className="muted">No uploads in this range.</p>}
                {data.recentUploads.map((v) => (
                  <button
                    key={v.ytVideoId}
                    className="flex w-full items-center justify-between rounded-lg px-3 py-2 text-left hover:bg-ink-700/50"
                    onClick={() => window.open(`https://www.youtube.com/watch?v=${v.ytVideoId}`, '_blank')}
                  >
                    <span className="truncate text-xs text-slate-300">{v.title}</span>
                    <span className="ml-3 shrink-0 text-[11px] text-slate-500">
                      <Badge tone={v.isShort ? 'brand' : 'neutral'}>{v.isShort ? 'Short' : 'Long'}</Badge>
                      <span className="ml-1.5">{formatRelative(v.publishedAt)}</span>
                    </span>
                  </button>
                ))}
              </div>
            </Card>

            <SourceNote>{data.sources.map((s) => `${s.source} - ${s.freshness} (confidence: ${s.confidence})`).join(' | ')}</SourceNote>
          </>
        )}
      </div>
    </div>
  );
}

function InsightGrid({ insights }: { insights: DashboardResponse['insights'] }): React.JSX.Element {
  const groups: { label: string; items: string[] }[] = [
    { label: 'What is working', items: insights.whatWorks },
    { label: 'Declining', items: insights.declining },
    { label: 'Best videos', items: insights.bestVideos },
    { label: 'Create next', items: insights.nextContent },
    { label: 'Metrics to watch', items: insights.watchMetrics },
  ];
  return (
    <div className="grid grid-cols-1 gap-3 lg:grid-cols-2">
      {groups.map((group) => (
        <div key={group.label} className="rounded-lg border border-ink-700 bg-ink-800/50 p-3">
          <p className="text-[11px] font-semibold uppercase tracking-wide text-slate-500">{group.label}</p>
          <ul className="mt-1.5 space-y-1">
            {group.items.length === 0 && <li className="text-xs text-slate-600">No signal in the current data.</li>}
            {group.items.map((item, i) => (
              <li key={i} className="text-xs leading-relaxed text-slate-300">
                {item}
              </li>
            ))}
          </ul>
        </div>
      ))}
    </div>
  );
}

function VideoList({ videos }: { videos: DashboardResponse['topVideos'] }): React.JSX.Element {
  if (videos.length === 0) return <p className="muted">Not enough data in this period.</p>;
  return (
    <div className="space-y-1.5">
      {videos.map((v) => (
        <button
          key={v.ytVideoId}
          className="flex w-full items-center justify-between gap-3 rounded-lg px-3 py-2 text-left hover:bg-ink-700/50"
          onClick={() => window.open(`https://www.youtube.com/watch?v=${v.ytVideoId}`, '_blank')}
        >
          <span className="truncate text-xs text-slate-300">{v.title}</span>
          <span className="shrink-0 text-[11px] text-slate-400">{formatCompact(v.stats.views)} views</span>
        </button>
      ))}
    </div>
  );
}
